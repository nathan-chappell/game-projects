/** Checked once at startup; IDs are the interface between HTML and controllers. */
export function element<K extends keyof GameElements>(id: K): GameElements[K];
export function element(id: string): HTMLElement;
export function element(id: string): HTMLElement {
  const found = document.getElementById(id);
  if (!found) throw new Error(`Missing game element: ${id}`);
  return found;
}
export type Elements = typeof element;

export function context2D(canvas: HTMLCanvasElement): CanvasRenderingContext2D {
  const context = canvas.getContext('2d');
  if (!context) throw new Error('This browser does not support Canvas 2D.');
  return context;
}
